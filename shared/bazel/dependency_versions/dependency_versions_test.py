"""Checks that dependency versions agree between Gradle, Bazel, and vendordeps.

gradle/libs.versions.toml is the source of truth. Bazel still pins some of the
same versions by hand in the files generated by
shared/bazel/thirdparty/integrity_helper.py, the bzlmodRio-opencv archive, and
the protoc-gen-quickbuf plugin URLs in MODULE.bazel. The AprilTag and
CameraServer vendordeps pin OpenCV too. This test fails if any of those drift
apart.
"""

import json
import re
import sys
import tomllib
from pathlib import Path

# Works both from the Bazel runfiles tree and from a source checkout.
ROOT = Path(__file__).resolve().parents[3]

OPENCV_GROUP = "org.wpilib.thirdparty.opencv"
VENDORDEPS = ["apriltag/AprilTag.json", "cameraserver/CameraServer.json"]

# Catalog version key -> file generated by integrity_helper.py from it.
GENERATED_THIRDPARTY = {
    "ceres": "shared/bazel/thirdparty/ceres/ceres.MODULE.bazel",
    "libsdlgpu": "shared/bazel/thirdparty/libsdlgpu/libsdlgpu.MODULE.bazel",
    "libssh": "shared/bazel/thirdparty/libssh/libssh.MODULE.bazel",
    "mrclib": "shared/bazel/thirdparty/mrclib/mrclib.MODULE.bazel",
}

QUICKBUF_PLUGIN_FILES = ["MODULE.bazel"]


def read(path: str) -> str:
    return (ROOT / path).read_text()


def load_catalog() -> dict:
    with open(ROOT / "gradle/libs.versions.toml", "rb") as f:
        return tomllib.load(f)


def check_generated_thirdparty(catalog: dict) -> list[str]:
    """integrity_helper.py output must match the catalog it was generated from."""
    errors = []
    for key, path in GENERATED_THIRDPARTY.items():
        version = catalog["versions"][key]
        match = re.search(r'^url_pattern = "([^"]+)"', read(path), re.MULTILINE)
        if not match or f"/{version}/" not in match.group(1):
            errors.append(
                f"{path} does not use {key} {version} from gradle/libs.versions.toml; "
                "rerun shared/bazel/thirdparty/integrity_helper.py"
            )
    return errors


def check_quickbuf_plugin(catalog: dict) -> list[str]:
    """The protoc-gen-quickbuf plugin must match quickbuf-runtime."""
    version = catalog["versions"]["quickbuf"]
    errors = []
    for path in QUICKBUF_PLUGIN_FILES:
        for found in sorted(
            set(re.findall(r"protoc-gen-quickbuf/([^/]+)/", read(path)))
        ):
            if found != version:
                errors.append(
                    f"{path}: protoc-gen-quickbuf {found}, "
                    f"gradle/libs.versions.toml quickbuf is {version}"
                )
    return errors


def check_opencv(catalog: dict) -> list[str]:
    """Native OpenCV and the vendordeps must match the Java OpenCV version."""
    version = catalog["versions"]["opencv"]
    found = []

    # bzlmodRio tags look like 2027.4.13.0-3.bcr1; the Maven form is 2027-4.13.0-3.
    for tag in re.findall(
        r"bzlmodRio-opencv/releases/download/([^/]+)/", read("MODULE.bazel")
    ):
        year, _, rest = re.sub(r"\.bcr\d+$", "", tag).partition(".")
        found.append((f"MODULE.bazel bzlmodRio-opencv {tag}", f"{year}-{rest}"))

    for path in VENDORDEPS:
        data = json.loads(read(path))
        for section in ("javaDependencies", "jniDependencies", "cppDependencies"):
            for dep in data.get(section, []):
                if dep.get("groupId") == OPENCV_GROUP:
                    found.append(
                        (f"{path} {section} {dep['artifactId']}", dep["version"])
                    )

    return [
        f"{where}: {v}, gradle/libs.versions.toml opencv is {version}"
        for where, v in found
        if v != version
    ]


def main() -> int:
    catalog = load_catalog()
    errors = (
        check_generated_thirdparty(catalog)
        + check_quickbuf_plugin(catalog)
        + check_opencv(catalog)
    )
    if errors:
        print("Dependency versions are out of sync:", file=sys.stderr)
        for error in errors:
            print(f"  {error}", file=sys.stderr)
        return 1
    print("All dependency versions agree with gradle/libs.versions.toml")
    return 0


if __name__ == "__main__":
    sys.exit(main())
